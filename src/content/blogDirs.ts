import generated from "virtual:blog-dirs";
import type { Section } from "./schema";
import { stripTrailingSlashes } from "@/lib/slashes";

/**
 * Directory listings for the static directories under /blog/ — driven by
 * a BLACKLIST, not a maintained file list.
 *
 * The blog's posts are static files served straight from public/blog/ —
 * markdown (`.md`, fetched and rendered as markdown) or authored Section
 * trees (`.json`, the exact shape the content files use, fetched and
 * mounted as native windows). The router addresses any extension-less
 * /blog/** URL as a post page and resolves the file behind it. That is
 * right for FILES and wrong for DIRECTORIES:
 * /blog/random is a folder on disk, its ".md" fetch resolves to nothing,
 * and the embed renders whatever the server's SPA fallback hands back.
 *
 * Two pieces cooperate:
 *
 * - src/content/blogDirs.json — GENERATED by scripts/refresh-content.mjs
 *   (a deterministic walk of public/blog/ on every refresh cycle). It
 *   lists every subdirectory and the files each holds. You never edit it;
 *   run `npm run refresh:content` after touching public/blog/ and commit
 *   the refreshed snapshot.
 *
 * - THIS FILE — the authored policy: which file-name patterns are HIDDEN
 *   from every listing (the blacklist), and per-directory overrides. A
 *   directory needs no entry at all: it lists automatically, minus the
 *   blacklisted files. Add an override only to bend the defaults.
 */
export type BlogDirOverride = {
  /** Replaces the default blacklist for this directory. Patterns are
   * globs over the file NAME ("*.png", "draft-*", "notes?.md"); an
   * empty array hides nothing. */
  hide?: string[];
  /** Extensions whose files are POSTS: their listing link drops the
   * extension, so the URL resolves to the post page that embeds the
   * file. Every other shown file links its raw asset. Markdown and
   * .json Section posts both address extension-less — one page per
   * file, whichever form it is authored in. */
  posts?: string[];
  /** The listing window's heading; defaults to the directory's name. */
  heading?: string;
};

/** The default blacklist, applied to EVERY directory listing: binary
 * assets and working files never list. Extend freely — patterns are
 * case-insensitive globs over the file name. */
export const blogDirDefaults: { hide: string[]; posts: string[] } = {
  hide: [
    "*.png",
    "*.gif",
    "*.jpg",
    "*.jpeg",
    "*.webp",
    "*.svg",
    "*.avif",
    "*.ico",
    "*.mp3",
    "*.mp4",
    "*.ogg",
    "*.wav",
    "*.woff2",
  ],
  posts: ["md", "json"],
};

/** Per-directory policy. Keyed by the directory's URL path exactly as
 * served (/blog/random). A directory absent here simply takes the
 * defaults; an override of exactly `false` opts the directory OUT of
 * listing entirely — the address stays a plain asset folder (its bare
 * URL answers 404, its files keep their direct URLs). */
export const blogDirOverrides: Record<string, BlogDirOverride | false> = {
  // The references folder is an asset shelf, not a post collection —
  // its PDF is linked from the blog post that cites it, and the folder
  // itself has no listing page.
  "/blog/references": false,
};

/** The generated snapshot: [{ path, files }, ...]. */
const directories = (
  generated as {
    directories: Array<{ path: string; files: string[]; dirs: string[] }>;
  }
).directories;

/** A glob pattern over a file name to a matcher: * runs over any run of
 * characters (no separators — names only), ? is a single character, and
 * everything else is literal. Case-insensitive: "*.PNG" hides ".png". */
const globMatcher = (pattern: string): ((name: string) => boolean) => {
  const source = pattern
    .replace(/[.+^${}()|[\]\\]/g, "\\$&")
    .replace(/\*/g, ".*")
    .replace(/\?/g, ".");
  const re = new RegExp(`^${source}$`, "i");
  return (name) => re.test(name);
};

/** Whether a directory serves a listing page: every generated directory
 * does, unless its override is exactly false. */
export const blogDirListed = (path: string): boolean =>
  blogDirOverrides[path] !== false;

const policyFor = (path: string) => {
  const override =
    blogDirOverrides[path] === false ? {} : (blogDirOverrides[path] ?? {});
  const hide = override.hide ?? blogDirDefaults.hide;
  return {
    hide: hide.map(globMatcher),
    posts: (override.posts ?? blogDirDefaults.posts).map((e) =>
      e.toLowerCase().replace(/^\./, ""),
    ),
    heading: override.heading,
  };
};

/** The configured directory addressed by a pathname, or undefined.
 * Comparison is decoded, slash-normalized and case-insensitive; a
 * malformed escape decodes to the raw path (same policy as the router's
 * normalizePath). */
/** The files a /blog directory holds, by its served path — including
 * the blog ROOT ("/blog"), whose files this exposes even though the
 * root itself never lists (the curated blog.json page lives there).
 * Answers undefined when the path names no directory in the walk —
 * which, for anything under /blog/, means some ancestor of the address
 * does not exist on the filesystem. */
export function blogDirFiles(path: string): string[] | undefined {
  let p = path;
  try {
    p = decodeURIComponent(path);
  } catch {
    /* keep the raw path */
  }
  p = stripTrailingSlashes(p).toLowerCase();
  return directories.find((dir) => dir.path.toLowerCase() === p)?.files;
}

/** The directory a pathname lists, or undefined. The blog ROOT is
 * excluded from listing lookups: /blog is the curated blog.json page,
 * never a directory listing. */
export function findBlogDir(pathname: string) {
  let path = pathname;
  try {
    path = decodeURIComponent(pathname);
  } catch {
    /* keep the raw path */
  }
  path = stripTrailingSlashes(path).toLowerCase();
  if (path === "/blog") return undefined;
  return directories.find((dir) => dir.path.toLowerCase() === path);
}

const extensionOf = (file: string): string => {
  const dot = file.lastIndexOf(".");
  return dot <= 0 ? "" : file.slice(dot + 1).toLowerCase();
};

/** The listing window for the directory a pathname addresses: one root
 * window (the directory's name, expanded) whose content is a markdown
 * list of the files that survive the blacklist. Post-extension files
 * link extension-less (the router's post page embeds their file); the
 * rest link the raw file directly. Returns undefined when the pathname
 * addresses no directory on disk — the caller decides what an
 * unconfigured address means. */
export function blogDirListing(pathname: string): Section | undefined {
  const dir = findBlogDir(pathname);
  if (!dir || !blogDirListed(dir.path)) return undefined;
  const policy = policyFor(dir.path);
  // Child directories first — the way deeper into the tree — each a
  // plain link to that directory's own listing page. Opted-out children
  // (override false) answer 404, so they never link.
  const dirs = dir.dirs
    .filter((child) => blogDirListed(child))
    .map((child) => {
      const name = child.split("/").filter(Boolean).pop() ?? child;
      return `- [${name}/](${child})`;
    });
  const shown = dir.files.filter(
    (file) =>
      !file.startsWith(".") && !policy.hide.some((matches) => matches(file)),
  );
  const lines = shown.map((file) => {
    const dot = file.lastIndexOf(".");
    const label = dot > 0 ? file.slice(0, dot) : file;
    const href = policy.posts.includes(extensionOf(file))
      ? `${dir.path}/${label}`
      : `${dir.path}/${file}`;
    return `- [${label}](${href})`;
  });
  return {
    heading:
      policy.heading ?? dir.path.split("/").filter(Boolean).pop() ?? dir.path,
    theme: "open",
    className: "blog-dir-listing",
    content: [...dirs, ...lines].join("\n"),
  };
}
